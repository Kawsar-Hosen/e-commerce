/** Recomputes tiers from demo sales so the badge matches the numbers shown. */
export function withComputedTier(seller: Seller): Seller {
  const tier = tierForSales(seller.totalSales);
  return { ...seller, tier, commissionRate: commissionRateForTier(tier) };
}

